const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: TKey) => string }>({
  lang: "en",
  setLang: () => {},
  t: (k) => k,
});

export function LanguageProvider({
  children,
  initialLang = "en",
}: {
  children: ReactNode;
  /** Must match SSR cookie value to avoid EN→RU flash and hydration mismatch. */
  initialLang?: Lang;
}) {
  const [lang, setLangState] = useState<Lang>(initialLang);

  // After LANG_INIT_SCRIPT migrates localStorage → cookie, align React before paint.
  useLayoutEffect(() => {
    if (typeof document === "undefined") return;
    const match = document.cookie.match(/(?:^|; )tf_lang=(ru|en)/);
    const cookieLang = parseLang(match?.[1]);
    if (cookieLang && cookieLang !== initialLang) {
      setLangState(cookieLang);
    }
  }, [initialLang]);

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    persistLang(l);
  };

  const t = (k: TKey) => dict[lang][k] ?? dict.en[k] ?? k;
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);

export function LanguageSwitcher({ className = "" }: { className?: string }) {
  const { lang, setLang } = useI18n();
  return (
    <div
      className={
        "inline-flex items-center rounded-lg border border-border/80 bg-card p-0.5 text-[11px] font-semibold shadow-soft " +
        className
      }
    >
      {(["en", "ru"] as Lang[]).map((l) => (
        <button
          key={l}
          type="button"
          onClick={() => setLang(l)}
          className={
            "rounded-md px-2 py-1 uppercase outline-none transition focus-visible:ring-2 focus-visible:ring-ring/35 " +
            (lang === l
              ? "bg-secondary text-foreground"
              : "text-muted-foreground hover:text-foreground")
          }
        >
          {l}
        </button>
      ))}
    </div>
  );
}
